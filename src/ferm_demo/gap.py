"""Build the gap report: which CSV columns needed new terms, and why."""

from __future__ import annotations

import json
from pathlib import Path

import yaml


def load_mapping(path: Path) -> dict:
    return yaml.safe_load(path.read_text())["columns"]


def summary(mapping: dict) -> dict[str, int]:
    out: dict[str, int] = {}
    for col in mapping.values():
        out[col["status"]] = out.get(col["status"], 0) + 1
    return dict(sorted(out.items()))


def cited_curies(mapping: dict) -> set[str]:
    curies = set()
    for col in mapping.values():
        curies.update(c for c in col.get("maps_to", []) if not c.startswith("FERM:"))
        curies.update(c["curie"] for c in col.get("checked", []))
    return curies


def render(mapping: dict, terms_file: Path) -> str:
    labels = {r["curie"]: r["ols_label"] for r in json.loads(terms_file.read_text())}
    counts = summary(mapping)
    lines = [
        "# Gap report",
        "",
        "Generated by `python -m ferm_demo.pipeline` from `ontology/column_mapping.yaml`.",
        "Do not edit by hand.",
        "",
        f"Columns: {len(mapping)}. " + ", ".join(f"{k}: {v}" for k, v in counts.items()) + ".",
        "",
        "## Columns with no fitting existing term",
        "",
        "| Column | Proposed term | Parent | Existing terms checked |",
        "|---|---|---|---|",
    ]
    for name, col in mapping.items():
        if col["status"] != "new":
            continue
        prop = col["proposed"]
        checked = "; ".join(f"{c['curie']} ({labels.get(c['curie'], '?')}): {c['why_not']}" for c in col.get("checked", []))
        lines.append(f"| `{name}` | {prop['label']} | {prop['parent']} | {checked or 'none found'} |")
    lines += ["", "## Notes on proposed terms", ""]
    for name, col in mapping.items():
        note = col.get("proposed", {}).get("note")
        if note:
            lines.append(f"* `{name}`: {note}")
    lines += ["", "## Columns covered by existing terms", ""]
    for name, col in mapping.items():
        if col["status"] == "reused":
            terms = ", ".join(f"{c} ({labels.get(c, '?')})" for c in col["maps_to"])
            lines.append(f"* `{name}`: {terms}")
            for c in col.get("checked", []):
                lines.append(f"  * also checked {c['curie']} ({labels.get(c['curie'], '?')}): {c['why_not']}")
            if col.get("note"):
                lines.append(f"  * note: {col['note']}")
    lines += ["", "## Local columns", ""]
    for name, col in mapping.items():
        if col["status"] == "local":
            lines.append(f"* `{name}`: {col.get('note', '')}")
    return "\n".join(lines) + "\n"
