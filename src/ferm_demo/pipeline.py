"""Run every step and write the results the README quotes.

    uv run python -m ferm_demo.pipeline

Writes build/instances.ttl, build/provenance.ttl, results/results.json and
results/gap_report.md.
"""

from __future__ import annotations

import json
import re
import sys

from rdflib import Graph
from rdflib.namespace import RDF

from . import checks, gap
from . import namespaces as ns
from .convert import convert, load_ontology
from .linkml_check import validate_csv
from .paths import (
    BROKEN_CSV,
    BUILD,
    COLUMN_MAPPING,
    EXTERNAL_TERMS,
    LINKML_SCHEMA,
    ONTOLOGY,
    QUERIES,
    RESULTS,
    ROOT,
    RUNS_CSV,
    SHAPES,
)
from .queries import run_all
from .shacl import validate_data


def planted_inconsistency(onto: Graph, data: Graph) -> list[str]:
    """Type one run as a bioreactor too; BFO disjointness should make this inconsistent."""
    g = onto + data
    g.add((ns.DATA["run/R01"], RDF.type, ns.BIOREACTOR))
    return checks.owl_rl_errors(g)


def run() -> dict:
    onto = load_ontology(ONTOLOGY)
    good = convert(RUNS_CSV)
    broken = convert(BROKEN_CSV)

    BUILD.mkdir(exist_ok=True)
    good.data.serialize(BUILD / "instances.ttl", format="turtle")
    good.provenance.serialize(BUILD / "provenance.ttl", format="turtle")

    combined = onto + good.data
    shacl_ok, shacl_good = validate_data(good.data, SHAPES)
    shacl_broken_ok, shacl_broken = validate_data(broken.data, SHAPES)
    mapping = gap.load_mapping(COLUMN_MAPPING)
    external = json.loads(EXTERNAL_TERMS.read_text())

    results = {
        "ontology": checks.term_stats(onto),
        "external_terms": {
            "looked_up_in_ols": len(external),
            "verified": sum(r["verified"] for r in external),
            "used_in_ontology": len(checks.ontology_obo_iris(onto)),
            "used_but_not_verified": checks.external_iri_problems(onto, EXTERNAL_TERMS),
        },
        "metadata_problems": checks.missing_metadata(onto),
        "conversion": {
            "csv_rows": good.rows,
            "instance_triples": len(good.data),
            "provenance_records": len(set(good.provenance.subjects(RDF.type, RDF.Statement))),
            "provenance_triples": len(good.provenance),
        },
        "reasoning_owl_rl": {
            "errors_ontology_plus_data": checks.owl_rl_errors(combined),
            "unsatisfiable_ferm_classes": checks.unsatisfiable_ferm_classes(onto),
            "planted_inconsistency_errors": planted_inconsistency(onto, good.data),
        },
        "shacl": {
            "runs_csv_conforms": shacl_ok,
            "runs_csv_violations": len(shacl_good),
            "broken_csv_conforms": shacl_broken_ok,
            "broken_csv_violations": [v.__dict__ for v in shacl_broken],
        },
        "linkml": {
            "runs_csv_errors": validate_csv(RUNS_CSV, LINKML_SCHEMA),
            "broken_csv_errors": validate_csv(BROKEN_CSV, LINKML_SCHEMA),
        },
        "gap_report": gap.summary(mapping),
        "queries": run_all(combined, QUERIES),
    }

    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "results.json").write_text(json.dumps(results, indent=2) + "\n")
    (RESULTS / "gap_report.md").write_text(gap.render(mapping, EXTERNAL_TERMS))
    return results


START, END = "<!-- results:start -->", "<!-- results:end -->"


def _table(rows: list[dict]) -> list[str]:
    cols = list(rows[0])
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in rows:
        out.append("| " + " | ".join(str(row[c]).rsplit("/", 1)[-1] for c in cols) + " |")
    return out


def readme_block(r: dict) -> str:
    """Markdown for the README, built only from results.json."""
    o, c, ext = r["ontology"], r["conversion"], r["external_terms"]
    rl, sh, lm = r["reasoning_owl_rl"], r["shacl"], r["linkml"]
    lines = [
        START,
        "<!-- generated by `uv run python -m ferm_demo.pipeline` from results/results.json -->",
        "",
        "| What | Number |",
        "|---|---|",
        f"| Classes in `ferm.ttl` (FERM / reused) | {o['classes']} ({o['ferm_classes']} / {o['external_classes']}) |",
        f"| Properties (FERM / reused) | {o['properties']} ({o['ferm_properties']} / {o['external_properties']}) |",
        f"| Triples in `ferm.ttl` | {o['ontology_triples']} |",
        f"| External IRIs looked up in OLS / verified | {ext['looked_up_in_ols']} / {ext['verified']} |",
        f"| External IRIs used in the ontology but not verified | {len(ext['used_but_not_verified'])} |",
        f"| CSV rows converted | {c['csv_rows']} |",
        f"| Instance triples | {c['instance_triples']} |",
        f"| Provenance records (one per derived triple and source cell) | {c['provenance_records']} |",
        f"| OWL RL errors on ontology plus data | {len(rl['errors_ontology_plus_data'])} |",
        f"| OWL RL errors after planting a run typed as a bioreactor | {len(rl['planted_inconsistency_errors'])} |",
        f"| SHACL violations, `runs.csv` | {sh['runs_csv_violations']} |",
        f"| SHACL violations, `broken_runs.csv` | {len(sh['broken_csv_violations'])} |",
        f"| LinkML errors, `runs.csv` / `broken_runs.csv` | {len(lm['runs_csv_errors'])} / {len(lm['broken_csv_errors'])} |",
        f"| CSV columns needing a new term (gap report) | {r['gap_report'].get('new', 0)} of {sum(r['gap_report'].values())} |",
        "",
        "SHACL messages for the broken record:",
        "",
    ]
    lines += [f"* `{v['focus'].rsplit('/data/', 1)[-1]}`: {v['message']}" for v in sh["broken_csv_violations"]]
    for name, rows in r["queries"].items():
        lines += ["", f"Query `{name}.rq`:", ""]
        lines += _table(rows) if rows else ["(no rows)"]
    lines += ["", END]
    return "\n".join(lines)


def update_readme(r: dict, check: bool) -> bool:
    readme = ROOT / "README.md"
    text = readme.read_text()
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: readme_block(r), text, flags=re.S)
    if check:
        return new == text
    readme.write_text(new)
    return True


def main() -> None:
    check = "--check" in sys.argv
    r = run()
    if not update_readme(r, check):
        sys.exit("README results block is out of date; run the pipeline without --check")
    print(json.dumps({k: r[k] for k in ("ontology", "conversion", "gap_report")}, indent=2))
    print("SHACL violations in broken_runs.csv:", len(r["shacl"]["broken_csv_violations"]))
    print("OWL RL errors on ontology plus data:", len(r["reasoning_owl_rl"]["errors_ontology_plus_data"]))


if __name__ == "__main__":
    main()
